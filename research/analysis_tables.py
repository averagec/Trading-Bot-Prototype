def _clean(o):
    if isinstance(o, dict):
        return {str(k): _clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [_clean(v) for v in o]
    if isinstance(o, (np.floating, float)):
        return None if o != o else float(o)
    if isinstance(o, np.integer):
        return int(o)
    if isinstance(o, np.bool_):
        return bool(o)
    return o


def _seen_window(specs, syms) -> dict:
    """Descriptive numbers from the already-seen 2025-05+ base run (no flatten, ATR-scaled risk, pessimistic conventions)."""
    from research.data import prepare_bars
    p = A.OUT / "v1" / "base_faithful" / "trades.csv"
    if not p.exists():
        return {"md": "(research/output/v1/base_faithful/trades.csv not found)", "json": {}}
    t = pd.read_csv(p)
    t["placed_T"] = pd.to_datetime(t["placed_T"], utc=True)
    if t["placed_T"].min() < A.FINAL_END_TS:
        return {"md": "(skipped: the trade file reaches into the FINAL window)", "json": {}}
    t = t[t["exit_reason"] != "END"].copy()
    for c in ("open_T", "close_T"):
        t[c] = pd.to_datetime(t[c], utc=True)
    wins = {s: A.weekend_windows(prepare_bars(s, start=A.SEEN_START, sentinel_missing=False, check_quality=False)["M5"]["time"]) for s in syms}
    t["cross"] = False
    t["at_reopen"] = False
    for s in syms:
        m = (t["symbol"] == s).to_numpy()
        if m.any():
            t.loc[m, "cross"] = A.crosses_closure(t.loc[m, "open_T"], t.loc[m, "close_T"], wins[s])
            t.loc[m, "at_reopen"] = t.loc[m, "close_T"].isin(set(pd.to_datetime(wins[s]["reopen_T"], utc=True))).to_numpy()
    h = t["placed_T"].dt.hour
    late = t[h >= 20]
    cr = t[t["cross"]]
    rr = t[t["at_reopen"]]
    js = {"n": len(t), "mean_r": float(t["r"].mean()), "late_n": len(late), "late_mean_r": float(late["r"].mean()),
          "cross_n": len(cr), "cross_mean_r": float(cr["r"].mean()), "cross_sum_r": float(cr["r"].sum()), "at_reopen_n": len(rr),
          "at_reopen_sum_r": float(rr["r"].sum()), "worst_r": float(t["r"].min()), "sun_decisions": int((t["placed_T"].dt.dayofweek == 6).sum())}
    md = (f"Base run 2025-05 to 2026-10 (n={js['n']}, mean {js['mean_r']:+.3f} R; no flatten, pessimistic conventions, ATR-scaled risk): "
          f"{js['cross_n']} trades crossed a weekend closure (mean {js['cross_mean_r']:+.2f} R, sum {js['cross_sum_r']:+.1f} R); "
          f"{js['at_reopen_n']} closed on the first bar after a reopen (sum {js['at_reopen_sum_r']:+.1f} R); worst trade {js['worst_r']:.1f} R; "
          f"{js['late_n']} decided at or after 20:00 UTC (mean {js['late_mean_r']:+.2f} R); Sunday decisions {js['sun_decisions']}.")
    return {"md": md, "json": js}
